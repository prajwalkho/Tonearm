import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { ROOT_DIR, scanSongs } from './song-catalog.mjs';

const songs = await scanSongs();
const safeJson = JSON.stringify(songs).replaceAll('<', '\\u003c');
const output = `// Generated by npm run build. Edit Songs/ and regenerate instead of editing this file.\nwindow.TONEARM_SONGS = ${safeJson};\n`;
await writeFile(join(ROOT_DIR, 'songs-manifest.js'), output, 'utf8');
console.log(`Generated songs-manifest.js with ${songs.length} song${songs.length === 1 ? '' : 's'}.`);
