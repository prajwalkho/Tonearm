import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { ROOT_DIR, scanSongs } from './song-catalog.mjs';

const manifestPath = join(ROOT_DIR, 'songs-manifest.js');
const generatedAt = new Date().toISOString();
let previousSongs = [];
try {
  const previousSource = await readFile(manifestPath, 'utf8');
  const previousJson = previousSource.match(/^window\.TONEARM_SONGS\s*=\s*(.+);$/m)?.[1];
  if (previousJson) previousSongs = JSON.parse(previousJson);
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}

const previousById = new Map(previousSongs.filter(song => Number.isSafeInteger(Number(song.id))).map(song => [Number(song.id), song]));
const songs = (await scanSongs()).map(song => {
  const prior = previousById.get(song.id);
  const priorDate = typeof prior?.addedAt === 'string' ? new Date(prior.addedAt) : null;
  const addedAt = priorDate && Number.isFinite(priorDate.getTime()) ? priorDate.toISOString() : generatedAt;
  return { ...song, addedAt };
});
const safeJson = JSON.stringify(songs).replaceAll('<', '\\u003c');
const output = `// Generated by node scripts/generate-song-manifest.mjs. Edit Songs/ and regenerate instead of editing this file.\nwindow.TONEARM_SONGS = ${safeJson};\n`;
await writeFile(manifestPath, output, 'utf8');
console.log(`Generated songs-manifest.js with ${songs.length} song${songs.length === 1 ? '' : 's'}.`);
